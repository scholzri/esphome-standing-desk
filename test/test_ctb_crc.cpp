#include "../components/desk_link/ctb_crc.h"
#include "harness.h"

namespace {

struct Vector {
  const char *name;
  uint8_t payload[32];
  size_t payload_len;
  uint8_t crc_lo, crc_hi;
};

// Ten six-byte keypad frames and both twenty-eight-byte config frames.
const Vector VECTORS[] = {
    {"recall preset 1", {0xAA, 0xFF, 0x00, 0x48}, 4, 0x2A, 0x3E},
    {"recall preset 2", {0xAA, 0xFF, 0x01, 0x48}, 4, 0x10, 0x33},
    {"recall preset 3", {0xAA, 0xFF, 0x02, 0x48}, 4, 0x5E, 0x24},
    {"recall preset 4", {0xAA, 0xFF, 0x03, 0x48}, 4, 0x64, 0x29},
    {"store preset 1", {0xAA, 0xFF, 0x00, 0x44}, 4, 0x2C, 0x85},
    {"store preset 2", {0xAA, 0xFF, 0x01, 0x44}, 4, 0x16, 0x88},
    {"store preset 3", {0xAA, 0xFF, 0x02, 0x44}, 4, 0x58, 0x9F},
    {"store preset 4", {0xAA, 0xFF, 0x03, 0x44}, 4, 0x62, 0x92},
    {"move up", {0xAA, 0xFF, 0x00, 0x50}, 4, 0x2B, 0x08},
    {"move down", {0xAA, 0xFF, 0x00, 0x60}, 4, 0x29, 0x64},
    {"display inch",
     {0xAA, 0xF2, 0x31, 0x00, 0xDC, 0x05, 0x00, 0x00, 0x05, 0x00, 0x90, 0x02,
      0x5D, 0x02, 0x38, 0x00, 0x05, 0x00, 0x08, 0x00, 0x04, 0x00, 0x02, 0x00,
      0x00, 0x00},
     26, 0x0B, 0xCC},
    {"display cm",
     {0xAA, 0xF2, 0x31, 0x00, 0xDC, 0x05, 0x01, 0x00, 0x05, 0x00, 0x90, 0x02,
      0x5D, 0x02, 0x38, 0x00, 0x05, 0x00, 0x08, 0x00, 0x04, 0x00, 0x02, 0x00,
      0x00, 0x00},
     26, 0x69, 0xED},
};

}  // namespace

TEST(crc16_matches_every_known_frame) {
  for (const auto &v : VECTORS) {
    uint16_t crc = ctb::crc16(v.payload, v.payload_len);
    CHECK_EQ((int) (crc & 0xFF), (int) v.crc_lo);
    CHECK_EQ((int) (crc >> 8), (int) v.crc_hi);
  }
}

TEST(crc_append_writes_low_byte_first) {
  uint8_t frame[6] = {0xAA, 0xFF, 0x00, 0x50};
  ctb::crc_append(frame, 4);
  CHECK_EQ((int) frame[4], 0x2B);
  CHECK_EQ((int) frame[5], 0x08);
}

TEST(crc_check_accepts_valid_and_rejects_corrupted) {
  uint8_t frame[6] = {0xAA, 0xFF, 0x00, 0x50, 0x2B, 0x08};
  CHECK(ctb::crc_check(frame, 6));
  frame[2] = 0x01;  // flip a payload byte
  CHECK(!ctb::crc_check(frame, 6));
}

TEST(crc_check_rejects_undersized_frames) {
  uint8_t frame[2] = {0xAA, 0xFF};
  CHECK(!ctb::crc_check(frame, 2));
}
